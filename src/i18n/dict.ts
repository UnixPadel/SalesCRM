export type TKey = keyof typeof DICT;

// Arapça sözlük her anahtarı taşımalı: eksik anahtar burada derleme hatası verir.
AR satisfies Record<TKey, string>;

const PLURAL = /\{(\w+), plural,((?:\s*(?:=\d+|\w+) \{(?:[^{}]|\{\w+\})*\})+)\s*\}/g;
const PLURAL_FORM = /(=\d+|\w+) \{((?:[^{}]|\{\w+\})*)\}/g;
const pluralRules = new Map<Lang, Intl.PluralRules>();
const categoryOf = (lang: Lang, n: number): string => {
  let r = pluralRules.get(lang);
  if (!r) pluralRules.set(lang, (r = new Intl.PluralRules(localeOf(lang))));
  return r.select(n);
};

/** ICU çoğul bloklarını çözer: tam eşleşme (`=0`) > dilin kategorisi (one, two, few, many) > `other`. */
function plural(lang: Lang, s: string, vars: Record<string, string | number>): string {
  return s.replace(PLURAL, (whole, name: string, body: string) => {
    const raw = vars[name];
    const n = Number(raw);
    if (raw === undefined || Number.isNaN(n)) return whole;
    const forms = new Map<string, string>();
    for (const m of body.matchAll(PLURAL_FORM)) forms.set(m[1]!, m[2]!);
    const pick = forms.get(`=${n}`) ?? forms.get(categoryOf(lang, n)) ?? forms.get("other") ?? "";
    return pick.split("#").join(String(raw));
  });
}

export function translate(lang: Lang, key: TKey | string, vars: Record<string, string | number> = {}): string {
  const entry = (DICT as Record<string, readonly [string, string]>)[key];
  let s = entry
    ? lang === "ar"
      ? ((AR as Record<string, string>)[key] ?? entry[1])
      : entry[lang === "tr" ? 0 : 1]
    : key;
  if (s.includes(", plural,")) s = plural(lang, s, vars);
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Aşama ve kayıp nedeni adı: Türkçe ve İngilizce API'den, Arapça `AR_REF`'ten (yoksa İngilizce). */
export function refName(
  lang: Lang,
  kind: "stage" | "reason",
  item: { code: string | number; nameTr: string; nameEn: string },
): string {
  if (lang === "tr") return item.nameTr;
  if (lang === "ar") return AR_REF[`${kind}.${item.code}`] ?? item.nameEn;
  return item.nameEn;
}
